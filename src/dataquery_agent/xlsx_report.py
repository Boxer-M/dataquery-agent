"""Export a validated, ungrouped business summary to XLSX bytes; no querying or tools."""
from collections.abc import Mapping
from decimal import Decimal, DecimalException
from io import BytesIO

from openpyxl import Workbook, load_workbook
from openpyxl.styles import Font

from .business_results import decimal_value


def generate_metric_xlsx(result: dict, metrics: Mapping[str, dict]) -> bytes:
    """Use UnifiedAgent response['result'] and its Catalog snapshot (service.metrics).

    This internal export boundary checks shape/precision, not database authorization.
    The caller must already have validated and authorized the supplied query results.
    Only one complete scalar summary window is supported by this two-column format.
    """
    if not isinstance(result, dict) or not isinstance(result.get('plan'), dict) or not isinstance(metrics, Mapping):
        raise ValueError('xlsx_requires_complete_scalar_summary')
    plan = result['plan']
    ids = plan.get('metric_ids', [])
    rows = result.get('results', [])
    if (not isinstance(plan, dict) or result.get('status') != 'ok'
            or plan.get('analysis_type') != 'summary' or plan.get('comparison_type')
            or plan.get('group_by') or not isinstance(plan.get('time_windows'), list) or len(plan['time_windows']) != 1
            or not isinstance(ids, list) or not 1 <= len(ids) <= 6
            or any(not isinstance(mid, str) for mid in ids) or len(set(ids)) != len(ids)
            or not isinstance(rows, list) or len(rows) != 1 or not isinstance(rows[0], dict)
            or rows[0].get('bucket') != 'all' or rows[0].get('month') is not None
            or result.get('truncated') or result.get('rows_truncated')):
        raise ValueError('xlsx_requires_complete_scalar_summary')
    values = rows[0].get('metrics')
    if not isinstance(values, dict) or set(values) != set(ids):
        raise ValueError('xlsx_metric_results_mismatch')
    entries = []
    for mid in ids:
        metadata = metrics.get(mid)
        name = metadata.get('name_zh') if isinstance(metadata, Mapping) else None
        cell = values[mid]
        if not isinstance(name, str) or not name.strip() or len(name) > 120 or not isinstance(cell, dict):
            raise ValueError('xlsx_missing_metric_metadata')
        raw = cell.get('value')
        if type(raw) not in (str, int, Decimal) or len(str(raw)) > 64:
            raise ValueError('xlsx_invalid_numeric_value')
        try:
            value = decimal_value(raw)
        except (DecimalException, ValueError):
            raise ValueError('xlsx_invalid_numeric_value') from None
        scale = max(0, -value.as_tuple().exponent)
        if len(value.as_tuple().digits) > 15 or value.copy_abs() >= 10 ** 15 or scale > 15:
            raise ValueError('xlsx_precision_unsupported')
        entries.append((name, value, '0' + ('.' + '0' * scale if scale else '')))

    workbook = Workbook()
    sheet = workbook.active
    sheet.title = '经营指标'
    sheet.append(['指标', '数值'])
    for header in sheet[1]:
        header.font = Font(name='Arial', bold=True)
    sheet.freeze_panes = 'A2'
    sheet.column_dimensions['A'].width = 36
    sheet.column_dimensions['B'].width = 22
    for index, (name, value, number_format) in enumerate(entries, 2):
        label = sheet.cell(index, 1, name)
        label.data_type = 's'  # Catalog labels remain literal text, never formulas.
        number = sheet.cell(index, 2, value)
        number.number_format = number_format
    output = BytesIO()
    workbook.save(output)
    workbook.close()
    content = output.getvalue()
    # Read only our own generated bytes, never an uploaded/untrusted workbook.
    restored = load_workbook(BytesIO(content), read_only=True, data_only=True, keep_links=False)
    try:
        for row, (name, value, number_format) in zip(restored.active.iter_rows(min_row=2), entries, strict=True):
            if (row[0].value != name or row[1].data_type != 'n'
                    or Decimal(str(row[1].value)) != value or row[1].number_format != number_format):
                raise ValueError('xlsx_precision_roundtrip_failed')
    finally:
        restored.close()
    return content
